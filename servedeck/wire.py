"""servedeck.wire — generated client configs (REDESIGN-2026-09-12.md §2.4).

The three ``render_*`` functions are PURE: given a :class:`servedeck.models.Registry`
and the CURRENT content of a client config file (as a string — ``""`` when the file
does not exist yet), each returns the new content. No filesystem access, no
`$HOME`, so they are fully testable with tmp_path-written fixtures.

Resolving ``ctx = "native"`` to an integer needs the local hub cache
(:func:`servedeck.models.native_ctx`), which IS I/O — so it is injected as a
``resolve_ctx`` callable rather than done inside the pure functions. Production
callers get one from :func:`make_default_ctx_resolver`; tests pass a trivial
dict-backed one and never touch ``$HOME``.

Every generator EDITS its own tables in place and leaves the rest of the file
byte-for-byte untouched (comments included) — a full parse-and-re-serialize
through ``tomllib``/``tomli_w`` would silently drop every hand-written comment
in ``~/.codex/config.toml``, which is exactly the "clobber" the packet's
instructions rule out. ``tomli_w`` is used only to render the VALUE of one
table at a time (correct quoting/escaping), never to rewrite the whole file.
"""

