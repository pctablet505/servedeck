BACKUP_ROOT = _paths.STATE_DIR / "backups"

#: Prepended to every table servedeck owns, so a human editing the file by hand
#: knows a `wire --apply` will overwrite it.
_OWNED_COMMENT = "# servedeck-generated by `servedeck wire` — edits here are overwritten."

CtxResolver = Callable[[_models.Model], int]


# --------------------------------------------------------------------------- #
# VS Code — chatLanguageModels.json (JSON: full parse/re-serialize is safe,
# there are no comments to lose).
# --------------------------------------------------------------------------- #

_VSCODE_GROUP_NAME = "servedeck"
#: The legacy local_llm-era group name this migrates in place, so `wire` does
#: not leave a stale duplicate group sitting next to the new one.
_VSCODE_OWNED_NAMES = frozenset({_VSCODE_GROUP_NAME, "local_llm"})
_DEFAULT_MAX_OUTPUT_TOKENS = 4096


def _vscode_entry(served_name: str, m: _models.Model, ctx: int) -> dict[str, Any]:
    max_out = m.max_output_tokens if m.max_output_tokens is not None else _DEFAULT_MAX_OUTPUT_TOKENS
    return {
        "id": served_name,
        "name": served_name,
        "url": CHAT_COMPLETIONS_URL,
        "toolCalling": True,
        "vision": m.vision,
        "maxInputTokens": max(ctx - max_out, 0),
        "maxOutputTokens": max_out,
    }


def render_vscode(
    registry: _models.Registry, existing_text: str, *, resolve_ctx: CtxResolver
) -> str:
    """One VS Code custom-endpoint group named "servedeck", one model entry per
    served id AND per preset. Any OTHER group in the array (a different vendor,
    or one the user added by hand) is passed through untouched."""
    if existing_text.strip():
        try:
            groups = json.loads(existing_text)
        except json.JSONDecodeError as e:
            raise ValueError(f"existing chatLanguageModels.json is not valid JSON: {e}") from e
        if not isinstance(groups, list):
            raise ValueError("chatLanguageModels.json must be a JSON array at the top level")
    else:
        groups = []

    entries: list[dict[str, Any]] = []
    for m in registry.models.values():
        ctx = resolve_ctx(m)
        entries.append(_vscode_entry(m.id, m, ctx))
        for preset_name in m.presets:
            entries.append(_vscode_entry(preset_name, m, ctx))

    new_group = {
        "name": _VSCODE_GROUP_NAME,
        "vendor": "customendpoint",
        "apiType": "chat-completions",
        "models": entries,
    }

    out: list[Any] = []
    replaced = False
    for g in groups:
        if isinstance(g, dict) and g.get("name") in _VSCODE_OWNED_NAMES:
            if not replaced:
                out.append(new_group)
                replaced = True
            continue  # drop a second owned group rather than duplicate it
        out.append(g)
    if not replaced:
        out.append(new_group)

    return json.dumps(out, indent=4) + "\n"


# --------------------------------------------------------------------------- #
# Comment-preserving TOML table surgery, shared by Codex and Kimi.
# --------------------------------------------------------------------------- #


def _find_top_level_section(text: str, header: str) -> tuple[int, int] | None:
    """Byte span of the table starting at the line ``header`` (exact match,
    trailing whitespace ignored), up to but not including the next line that
    starts with ``[`` (any top-level or dotted table header) or EOF. ``None``
    if ``header`` does not appear as its own line."""
    lines = text.splitlines(keepends=True)
    start = None
    for i, line in enumerate(lines):
        if line.rstrip("\n").rstrip("\r") == header:
            start = i
            break
    if start is None:
        return None
    end = len(lines)
    for j in range(start + 1, len(lines)):
        if lines[j].startswith("["):
            end = j
            break
    start_off = sum(len(l) for l in lines[:start])
    end_off = sum(len(l) for l in lines[:end])
    return start_off, end_off


def _render_table_values(data: dict[str, Any]) -> str:
    """key = value lines for ``data``, correctly TOML-quoted/escaped, via
    tomli_w (never a hand-rolled f-string) — but only the VALUES; the header
    line is ours, not tomli_w's, so callers can use quoted-dotted headers
    tomli_w itself would render differently (e.g. Kimi's ``models."x/y"``)."""
    if not data:
        return ""
    dumped = tomli_w.dumps({"_": data})
    # dumped is '[_]\nkey = "val"\n...\n' — drop the synthetic header line.
    return "\n".join(dumped.splitlines()[1:])


def _upsert_section(
    text: str, header: str, data: dict[str, Any], *, owned_comment: bool = True
) -> str:
    """Replace the ``[header]`` table's body with ``data`` (adding a leading
    "generated" comment), or append a new block if the table is not present
    yet. Everything outside the (comment +) header + body span is untouched."""
    body = _render_table_values(data)
    block = (f"{_OWNED_COMMENT}\n" if owned_comment else "") + header + "\n"
    if body:
        block += body + "\n"
    block += "\n"

    span = _find_top_level_section(text, header)
    if span is not None:
        start, end = span
        # Absorb one preceding line if it is exactly our own comment, so
        # re-running wire does not stack duplicate comments above the header.
        prefix_end = start
        preceding = text[:start].splitlines(keepends=True)
        if preceding and preceding[-1].rstrip("\n") == _OWNED_COMMENT:
            prefix_end = start - len(preceding[-1])
        return text[:prefix_end] + block + text[end:]

    if not text:
        return block
    sep = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + block


