def _kimi_capabilities(m: _models.Model) -> list[str]:
    caps: list[str] = []
    if m.tools is not None:
        caps.append("tool_use")
    if m.reasoning is not None:
        caps.extend(["thinking", "always_thinking"])
    if m.vision:
        caps.append("image_in")
    return caps


def _merge_thinking_section(text: str) -> str:
    """``[thinking] enabled = true`` — REDESIGN owner rule "reasoning always
    on". Any OTHER key already in ``[thinking]`` (e.g. ``effort``) is kept."""
    header = "[thinking]"
    span = _find_top_level_section(text, header)
    existing: dict[str, Any] = {}
    if span is not None:
        start, end = span
        try:
            existing = tomllib.loads(text[start:end]).get("thinking", {})
        except tomllib.TOMLDecodeError:
            existing = {}
    merged = dict(existing)
    merged["enabled"] = True
    return _upsert_section(text, header, merged, owned_comment=False)


def render_kimi(
    registry: _models.Registry, existing_text: str, *, resolve_ctx: CtxResolver
) -> str:
    """One ``[providers.servedeck]``, one ``[models."servedeck/<key>"]`` per
    model, and ``[thinking] enabled = true``. Everything else (the managed
    kimi-code provider, other models, oauth, services) is left untouched."""
    text = existing_text
    text = _upsert_section(
        text,
        "[providers.servedeck]",
        {"type": "openai", "base_url": f"{GATEWAY_BASE_URL}/v1", "api_key": "local-no-auth"},
    )
    for key, m in registry.models.items():
        ctx = resolve_ctx(m)
        data = {
            "provider": "servedeck",
            "model": m.id,
            "max_context_size": ctx,
            "capabilities": _kimi_capabilities(m),
            "display_name": m.id,
        }
        text = _upsert_section(text, f'[models."servedeck/{key}"]', data)
    text = _merge_thinking_section(text)
    return text


# --------------------------------------------------------------------------- #
# Wiring it together for the CLI (servedeck/cli.py) — the only I/O in this file.
# --------------------------------------------------------------------------- #


def make_default_ctx_resolver(registry: _models.Registry) -> CtxResolver:
    """A real ``resolve_ctx``: ``ctx`` as-is when it is already an int, else
    :func:`servedeck.models.native_ctx` (reads the local hub cache), cached per
    model so a preset-bearing model's hub lookup happens once per CLI run."""
    cache: dict[str, int] = {}

    def resolve(m: _models.Model) -> int:
        if isinstance(m.ctx, int):
            return m.ctx
        if m.key not in cache:
            cache[m.key] = _models.native_ctx(m.repo)
        return cache[m.key]

    return resolve


def read_existing(path: Path) -> str:
    """A target file's current content, or ``""`` if it does not exist yet."""
    try:
        return path.read_text()
    except FileNotFoundError:
        return ""


def unified_diff(name: str, before: str, after: str) -> str:
    return "".join(
        difflib.unified_diff(
            before.splitlines(keepends=True),
            after.splitlines(keepends=True),
            fromfile=f"a/{name}",
            tofile=f"b/{name}",
        )
    )


@dataclass(frozen=True)
class WireTarget:
    name: str
    path: Path
    render: Callable[[_models.Registry, str, CtxResolver], str]


